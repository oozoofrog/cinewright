import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {pathToFileURL} from 'node:url';
import {openRevision} from '../../../scripts/revisions.mjs';
import {exposure,sample} from '../../../runtime/timeline.mjs';
const out=path.dirname(new URL(import.meta.url).pathname);
const receipt=JSON.parse(await fs.readFile(path.join(out,'source-check-result.json')));
const frozen=await openRevision(path.join(out,'store'),receipt.revision);
const work=JSON.parse(await fs.readFile(path.join(frozen.root,'project/work.json')));
const {prepare}=await import(pathToFileURL(path.join(frozen.root,'project/scene.mjs')));
const light=work.layers.find(l=>l.config.role==='light');
const module=await prepare({frames:work.frames,span:n=>work.spans[n],sample},light.config);
const states=[108,109].map(frame=>{const e=exposure(light.exposure,frame);return {frame,exposed:e.frame,value:e.value,...module.evaluate({frame,exposed:e.frame,value:e.value})};});
assert.equal(states[0].exposed,102);assert.equal(states[1].exposed,102);
assert.deepEqual(states[0].phase,states[1].phase);
assert.deepEqual(states[0].keyOffset,states[1].keyOffset);
assert.equal(states[0].phase.hand,null);assert.equal(states[0].phase.keys,true);
assert.notEqual(states[0].lightX,states[1].lightX);
await fs.writeFile(path.join(out,'frozen-states.json'),JSON.stringify({revision:receipt.revision,states},null,2)+'\n');
console.log(JSON.stringify({revision:receipt.revision,states},null,2));
