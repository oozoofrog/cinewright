const digest = value => createHash('sha256').update(value).digest('hex');
function safe(name) {
  if (typeof name !== 'string' || !name || name.split('/').some(p => !/^[\w.-]+$/.test(p) || p === '.' || p === '..')) throw new Error(`Unsafe generated path: ${name}`);
  return name;
}
async function regularPath(root, name) {
  let current = root;
  for (const [index, part] of name.split('/').entries()) {
    current = path.join(current, part);
    let stat;
    try { stat = await fs.lstat(current); } catch (error) { if (error.code === 'ENOENT') return; throw error; }
    if (stat.isSymbolicLink() || (index < name.split('/').length - 1 ? !stat.isDirectory() : !stat.isFile())) throw new Error(`Generated path is not regular: ${name}`);
  }
}

/** Ownership ledger: only unchanged, previously generated bytes can be replaced.
 * Internal builder companion; all destinations are preflighted before any write.
 */
export async function writeOwnedFiles({ project, files, registry = '.cinewright-kit.json' }) {
  safe(registry);
  await fs.mkdir(project, { recursive: true });
  const root = await fs.realpath(project);
  await regularPath(root, registry);
  let ledger = { version: 1, generator: 'cinewright-owned-files', files: {} };
  try {
    ledger = JSON.parse(await fs.readFile(path.join(root, registry), 'utf8'));
    if (ledger.version !== 1 || ledger.generator !== 'cinewright-owned-files' || !ledger.files || typeof ledger.files !== 'object' || Array.isArray(ledger.files)) throw new Error(`Unknown ownership ledger: ${registry}`);
  } catch (error) { if (error.code !== 'ENOENT') throw error; }
  const writes = [];
  for (const [name, bytes] of Object.entries(files)) {
    safe(name);
    if (name === registry) throw new Error('Ownership ledger cannot own itself');
    await regularPath(root, name);
    const destination = path.join(root, name);
    let current;
    try { current = await fs.readFile(destination); } catch (error) { if (error.code !== 'ENOENT') throw error; }
    if (current && (!Object.hasOwn(ledger.files, name) || digest(current) !== ledger.files[name])) throw new Error(`Refusing to overwrite authored/unknown file: ${name}`);
    const data = Buffer.from(bytes);
    writes.push({ name, destination, data, hash: digest(data) });
  }
  for (const { name, destination, data, hash } of writes) {
    await fs.mkdir(path.dirname(destination), { recursive: true });
    await fs.writeFile(destination, data);
    ledger.files[name] = hash;
  }
  await fs.writeFile(path.join(root, registry), JSON.stringify(ledger, null, 2) + '\n');
  return writes.map(({ name, hash }) => ({ file: name, sha256: hash }));
}

/** Copy selected public modules AND dependencies into project/modules; no external imports.
 * Accepted names are the catalog keys above, including original motion/focus/accent/particles/artwork and independent animation/2D FX helpers.
 */
export async function materializeKit({ project, modules }) {
  if (!Array.isArray(modules) || !modules.length) throw new Error('materializeKit: select at least one module');
  const selected = new Set();
  function add(name) {
    if (!Object.hasOwn(catalog, name)) throw new Error(`materializeKit: unknown module ${name}`);
    if (selected.has(name)) return;
    catalog[name].dependencies.forEach(add);
    selected.add(name);
  }
  modules.forEach(add);
  const files = {};
  for (const name of selected) {
    const file = catalog[name].file;
    files[`modules/${file}`] = await fs.readFile(path.join(library, file));
  }
  return { modules: [...selected], files: await writeOwnedFiles({ project, files }) };
}
